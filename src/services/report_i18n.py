def normalize_language(code: str | None) -> str:
    """Accept 'ta', 'TA', 'ta-IN', 'Tamil', 'தமிழ்' -> 'ta' (unknown -> 'en')."""
    if not code:
        return "en"
    code = code.strip()
    if code in LANGUAGES:
        return code
    lowered = code.lower()
    for key, (native, english) in LANGUAGES.items():
        if lowered in (key.lower(), native.lower(), english.lower()):
            return key
    base = lowered.split("-")[0].split("_")[0]
    return base if base in LANGUAGES else "en"


def has_builtin(lang: str) -> bool:
    return lang in BUILTIN_LANGUAGES


def t(lang: str, key: str, **kwargs) -> str:
    """Label in `lang`, falling back to English for AI-only languages."""
    text = _STRINGS.get(lang, {}).get(key) or _EN[key]
    return text.format(**kwargs) if kwargs else text


def tv(lang: str, value: str | None) -> str:
    """Translate a value word (signal, rating, level); unknown words pass through."""
    if not value:
        return ""
    key = str(value).strip().lower().replace(" ", "_")
    return _VALUES.get(lang, {}).get(key) or _EN_VALUES.get(key) or str(value).replace("_", " ")


def language_name(lang: str) -> str:
    native, english = LANGUAGES.get(lang, (lang, lang))
    return english
